const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
let observer: MutationObserver | null = null;

function translated(value: string): string {
  const trimmed = value.trim();
  const replacement = english[trimmed];
  if (!replacement) {
    const dynamic: Array<[RegExp, string | ((...args: string[]) => string)]> = [
      [/^(\d+) movimientos?$/, "$1 transactions"],
      [/^(\d+) movimientos? por clasificar$/, "$1 transactions to categorize"],
      [/^(\d+) movimientos? · (.+) · ([A-Z]{3})$/, "$1 transactions · $2 · $3"],
      [/^Ver (\d+) grupos?$/, "View $1 groups"],
      [/^Movimientos del (.+)$/, "Transactions on $1"],
      [/^(\d+)% usado$/, "$1% used"],
      [/^Faltarían (.+)$/, "$1 short"],
      [/^Meta estimada: (.+)$/, "Estimated target: $1"],
      [/^Año estimado (\d+)$/, "Estimated year $1"],
      [/^(\d+) años$/, "$1 years"],
      [/^en (\d+) años$/, "in $1 years"],
      [/^Caja en (\d+) días$/, "Cash in $1 days"],
      [/^Mínimo: (.+)$/, "Minimum: $1"],
      [/^Hasta próximo ingreso \((.+)\)$/, "Until next income ($1)"],
      [/^Portafolio en (\d+) años$/, "Portfolio in $1 years"],
      [/^Precios al (.+)$/, "Prices as of $1"],
      [/^(.+) unidades · Costo prom\. (.+)$/, "$1 units · Avg. cost $2"],
      [/^(.+) aportados de (.+)$/, "$1 contributed of $2"],
      [/^(.+) disponible$/, "$1 available"],
      [/^Elegir a qué meses copiar (.+)$/, "Choose which months to copy $1 to"],
      [/^Person B tendría (.+) y Person A (.+) años\.$/, "Person B would be $1 and Person A would be $2 years old."],
      [/^(\d+)% · sugerido por (.+)$/, "$1% · suggested by $2"],
      [/^Mensual · desde (.+)$/, "Monthly · starting $1"],
      [/^Semanal · desde (.+)$/, "Weekly · starting $1"],
      [/^Cada 2 semanas · desde (.+)$/, "Every 2 weeks · starting $1"],
      [/^Anual · desde (.+)$/, "Yearly · starting $1"],
    ];
    let result = value.replace(/\b(Enero|Febrero|Marzo|Abril|Mayo|Junio|Julio|Agosto|Septiembre|Octubre|Noviembre|Diciembre)\b/g, (month) => english[month]);
    const resultTrimmed = result.trim();
    for (const [pattern, target] of dynamic) {
      if (!pattern.test(resultTrimmed)) continue;
      const translatedValue = resultTrimmed.replace(pattern, target as string);
      const start = result.slice(0, result.indexOf(resultTrimmed));
      const end = result.slice(result.indexOf(resultTrimmed) + resultTrimmed.length);
      return `${start}${translatedValue}${end}`;
    }
    return result;
  }
  const start = value.slice(0, value.indexOf(trimmed));
  const end = value.slice(value.indexOf(trimmed) + trimmed.length);
  return `${start}${replacement}${end}`;
}

function translateNode(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node as Text;
    const value = text.nodeValue || "";
    if (!value.trim()) return;
    const next = translated(value);
    if (next === value) return;
    if (!originalText.has(text)) originalText.set(text, value);
    text.nodeValue = next;
    return;
  }
  if (!(node instanceof Element)) return;
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    const value = node.getAttribute(attribute);
    if (!value) continue;
    const next = translated(value);
    if (next === value) continue;
    let stored = originalAttributes.get(node);
    if (!stored) { stored = new Map(); originalAttributes.set(node, stored); }
    if (!stored.has(attribute)) stored.set(attribute, value);
    node.setAttribute(attribute, next);
  }
  node.childNodes.forEach(translateNode);
}

function restoreNode(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const original = originalText.get(node as Text);
    if (original !== undefined) (node as Text).nodeValue = original;
    return;
  }
  if (!(node instanceof Element)) return;
  const attributes = originalAttributes.get(node);
  attributes?.forEach((value, name) => node.setAttribute(name, value));
  node.childNodes.forEach(restoreNode);
}

export function applyLanguage(language: Language) {
  observer?.disconnect();
  observer = null;
  document.documentElement.lang = language;
  if (language === "es") {
    restoreNode(document.body);
    return;
  }
  translateNode(document.body);
  observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateNode(mutation.target);
      mutation.addedNodes.forEach(translateNode);
    }
  });
  observer.observe(document.body, {subtree:true, childList:true, characterData:true});
}
